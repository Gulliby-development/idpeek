fn parse_iso_rejects_invalid_dates_and_clock_syntax() {
    let invalid = [
        "",
        "0000-01-01",
        "0000-02-29",
        "2024-00-01",
        "2024-13-01",
        "2024-01-00",
        "2024-04-31",
        "2024-02-30",
        "1900-02-29",
        "2100-02-29",
        "0001-02-29",
        "2024-2-01",
        "2024-02-1",
        "999-01-01",
        "２０２４-01-01",
        "2024-02-29T24:00:00Z",
        "2024-02-29T00:60:00Z",
        "2024-02-29T00:00:60Z",
        "2024-02-29T00:00:00",
        "2024-02-29T00:00:00z",
        "2024-02-29T00:00:00+00:00",
        "2024-02-29T00:00:00.Z",
        "2024-02-29T00:00:00.1234Z",
        "2024-02-29T00:00:00.１２Z",
        "2024-02-29T00:00:00ZZ",
        "2024-02-29TT00:00:00Z",
        "2024-02-29T00:00Z",
        "2024-02-29T0:00:00Z",
        "2024-02-29T00:00:0Z",
        "2024-02-29T00:00:00.1",
        "2024-02-29\n",
    ];

    for input in invalid {
        assert_eq!(parse_iso(input), Err(()), "{input:?}");
    }
}

#[test]
fn format_iso_matches_handwritten_utc_values_and_expanded_years() {
    let cases = [
        (-62_135_596_800_000, "0001-01-01T00:00:00.000Z"),
        (-12_219_292_800_000, "1582-10-15T00:00:00.000Z"),
        (-2_208_988_800_000, "1900-01-01T00:00:00.000Z"),
        (-86_400_000, "1969-12-31T00:00:00.000Z"),
        (-1_000, "1969-12-31T23:59:59.000Z"),
        (-1, "1969-12-31T23:59:59.999Z"),
        (0, "1970-01-01T00:00:00.000Z"),
        (1, "1970-01-01T00:00:00.001Z"),
        (86_399_999, "1970-01-01T23:59:59.999Z"),
        (946_684_800_000, "2000-01-01T00:00:00.000Z"),
        (1_709_296_200_500, "2024-03-01T12:30:00.500Z"),
        (281_474_976_710_655, "10889-08-02T05:31:50.655Z"),
    ];

    for (milliseconds, expected) in cases {
        assert_eq!(format_iso(milliseconds), expected);
    }
}

#[test]
fn format_iso_and_parse_iso_round_trip_handwritten_values() {
    let cases = [
        -62_135_596_800_000,
        -12_219_292_800_000,
        -1,
        0,
        1,
        86_399_999,
        946_684_800_000,
        1_709_251_200_000,
        1_709_296_200_500,
        281_474_976_710_655,
    ];

    for milliseconds in cases {
        let formatted = format_iso(milliseconds);
        assert_eq!(
            parse_iso(&formatted),
            Ok(ParsedTime::Milliseconds(milliseconds)),
            "{formatted}"
        );
    }
}

#[test]
fn format_duration_handles_subday_and_day_boundaries() {
    let cases = [
        (0, "00:00:00.000"),
        (1, "00:00:00.001"),
        (999, "00:00:00.999"),
        (1_000, "00:00:01.000"),
        (59_999, "00:00:59.999"),
        (60_000, "00:01:00.000"),
        (3_599_999, "00:59:59.999"),
        (3_600_000, "01:00:00.000"),
        (86_399_999, "23:59:59.999"),
        (86_400_000, "1d 00:00:00.000"),
        (90_061_001, "1d 01:01:01.001"),
        (172_800_000, "2d 00:00:00.000"),
        (-1, "00:00:00.001"),
        (-86_400_001, "1d 00:00:00.001"),
        (i64::MIN, "106751991167d 07:12:55.808"),
    ];

    for (milliseconds, expected) in cases {
        assert_eq!(format_duration(milliseconds), expected);
    }
}
