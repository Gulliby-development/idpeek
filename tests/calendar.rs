use idpeek::calendar::{ParsedTime, format_duration, format_iso, parse_iso};

#[test]
fn parse_iso_accepts_handwritten_dates_and_timestamp_boundaries() {
    let cases = [
        ("0001-01-01", -62_135_596_800_000),
        ("0004-02-29", -62_035_891_200_000),
        ("1582-10-15T00:00:00Z", -12_219_292_800_000),
        ("1900-01-01", -2_208_988_800_000),
        ("1970-01-01", 0),
        ("1970-01-01T00:00:00.001Z", 1),
        ("1970-01-01T00:00:01.5Z", 1_500),
        ("1970-01-01T00:00:01.50Z", 1_500),
        ("1970-01-01T00:00:01.500Z", 1_500),
        ("1970-01-02", 86_400_000),
        ("1969-12-31", -86_400_000),
        ("1969-12-31T23:59:59Z", -1_000),
        ("1969-12-31T23:59:59.999Z", -1),
        ("2000-01-01", 946_684_800_000),
        ("2000-02-29", 951_782_400_000),
        ("2024-02-29", 1_709_164_800_000),
        ("2024-02-29T23:59:59.999Z", 1_709_251_199_999),
        ("2024-03-01", 1_709_251_200_000),
        ("2024-03-01T12:30:00Z", 1_709_296_200_000),
        ("2024-03-01T12:30:00.5Z", 1_709_296_200_500),
        ("2024-03-01T12:30:00.05Z", 1_709_296_200_050),
        ("2024-03-01T12:30:00.005Z", 1_709_296_200_005),
        ("00001-01-01", -62_135_596_800_000),
        ("10889-08-02T05:31:50.655Z", 281_474_976_710_655),
    ];

    for (input, expected) in cases {
        assert_eq!(
            parse_iso(input),
            Ok(ParsedTime::Milliseconds(expected)),
            "{input}"
        );
    }
}

#[test]
fn parse_iso_preserves_valid_dates_outside_the_signed_millisecond_range() {
    assert_eq!(
        parse_iso("999999999999999999999999999999999999999-01-01"),
        Ok(ParsedTime::OutOfRange)
    );
    assert_eq!(
        parse_iso("100000000000000000000000000000000000000-02-29"),
        Ok(ParsedTime::OutOfRange)
    );
    assert_eq!(
        parse_iso("999999999999999999999999999999999999999-01-01T23:59:59.999Z"),
        Ok(ParsedTime::OutOfRange)
    );
}

